/** Overall threat score (mean of four dimensions). */
export function overallThreat(f: ThreatFactor): number {
  return Math.round((f.poaching + f.climate + f.habitatLoss + f.invasiveSpecies) / 4);
}

/** Return true if the stored primaryThreat matches one of the max-scored dimensions. */
export function primaryThreatMatches(f: ThreatFactor): boolean {
  const scores = { poaching: f.poaching, climate: f.climate, habitatLoss: f.habitatLoss, invasiveSpecies: f.invasiveSpecies };
  const max = Math.max(...Object.values(scores));
  return scores[f.primaryThreat] === max;
}